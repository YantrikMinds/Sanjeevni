-- IBM Db2 Enterprise Schema Definition
-- Optimized for IBM Db2 for LUW (Linux, UNIX, Windows) & IBM Cloud Db2
-- Managed via IBM Db2 Developer Extension for VS Code
-- =====================================================================

-- 1. ROVER FLEET TELEMETRY & HARDWARE REGISTRY
CREATE TABLE SANJEEVNI_FLEET (
    NODE_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    DEVICE_NAME VARCHAR(64) NOT NULL,
    MODEL VARCHAR(32) NOT NULL,
    STATUS VARCHAR(16) DEFAULT 'STANDBY',
    BATTERY_PCT SMALLINT DEFAULT 100,
    MESH_RSSI_DBM SMALLINT DEFAULT -65,
    IMU_TILT_DEG DECIMAL(5,2) DEFAULT 0.0,
    CH4_METHANE_PPM DECIMAL(6,2) DEFAULT 0.0,
    CO_PPM DECIMAL(6,2) DEFAULT 0.0,
    VOID_CLEARANCE_M DECIMAL(4,2) DEFAULT 1.0,
    LAST_SEEN_TS TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    ASSIGNED_SECTOR VARCHAR(64)
);

-- 2. DISASTER SECTORS & STRUCTURAL COLLAPSE ZONES
CREATE TABLE SANJEEVNI_SECTORS (
    SECTOR_CODE VARCHAR(16) NOT NULL PRIMARY KEY,
    SECTOR_NAME VARCHAR(128) NOT NULL,
    COLLAPSE_TYPE VARCHAR(32) NOT NULL, -- 'PANCAKE', 'LEAN_TO', 'CANTILEVER', 'V_SHAPE'
    HAZARD_LEVEL VARCHAR(16) DEFAULT 'HIGH', -- 'CRITICAL', 'HIGH', 'MODERATE', 'CLEARED'
    LATITUDE DECIMAL(9,6) NOT NULL,
    LONGITUDE DECIMAL(9,6) NOT NULL,
    ASSIGNED_NODE VARCHAR(32),
    ESTIMATED_VICTIMS SMALLINT DEFAULT 0,
    CLEARANCE_CORRIDOR_SAFE CHAR(1) DEFAULT 'Y',
    CONSTRAINT FK_SECTOR_ROVER FOREIGN KEY (ASSIGNED_NODE) REFERENCES SANJEEVNI_FLEET(NODE_ID)
);

-- 3. DETECTED SURVIVORS & EDGE AI RECON LOG
CREATE TABLE SANJEEVNI_SURVIVORS (
    DETECTION_ID INT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1001, INCREMENT BY 1) PRIMARY KEY,
    DETECTED_BY_NODE VARCHAR(32) NOT NULL,
    SECTOR_CODE VARCHAR(16) NOT NULL,
    DETECTION_CLASS VARCHAR(32) DEFAULT 'HUMAN LIMB',
    CONFIDENCE_PCT DECIMAL(5,2) NOT NULL,
    DETECTED_LAT DECIMAL(9,6) NOT NULL,
    DETECTED_LNG DECIMAL(9,6) NOT NULL,
    DETECTION_TIMESTAMP TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    STATUS VARCHAR(24) DEFAULT 'AWAITING_DISPATCH', -- 'AWAITING_DISPATCH', 'DISPATCHED', 'EVACUATED'
    DISPATCH_TOKEN VARCHAR(64),
    COMMANDER_SIGNOFF VARCHAR(64),
    CONSTRAINT FK_SURVIVOR_ROVER FOREIGN KEY (DETECTED_BY_NODE) REFERENCES SANJEEVNI_FLEET(NODE_ID),
    CONSTRAINT FK_SURVIVOR_SECTOR FOREIGN KEY (SECTOR_CODE) REFERENCES SANJEEVNI_SECTORS(SECTOR_CODE)
);

-- 4. UN INSARAG AUDIT TRAIL & RESCUE DISPATCH SIGN-OFF
CREATE TABLE SANJEEVNI_DISPATCH_LOG (
    DISPATCH_ID INT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 5001, INCREMENT BY 1) PRIMARY KEY,
    DETECTION_ID INT NOT NULL,
    COMMANDER_NAME VARCHAR(64) NOT NULL,
    ACTION_TAKEN VARCHAR(32) NOT NULL, -- 'DISPATCH_USAR', 'MODIFY_ROUTE', 'OVERRIDE'
    SIGN_OFF_HASH VARCHAR(64) NOT NULL,
    DISPATCH_TIMESTAMP TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    HOSPITAL_DESTINATION VARCHAR(128),
    CONSTRAINT FK_DISPATCH_SURVIVOR FOREIGN KEY (DETECTION_ID) REFERENCES SANJEEVNI_SURVIVORS(DETECTION_ID)
);

-- INDEXES FOR ULTRA-FAST SUB-SECOND INCIDENT RETRIEVAL
CREATE INDEX IDX_SURVIVOR_STATUS ON SANJEEVNI_SURVIVORS (STATUS, CONFIDENCE_PCT DESC);
CREATE INDEX IDX_FLEET_STATUS ON SANJEEVNI_FLEET (STATUS, BATTERY_PCT);
CREATE INDEX IDX_SECTOR_HAZARD ON SANJEEVNI_SECTORS (HAZARD_LEVEL);
